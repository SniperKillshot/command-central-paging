"""Build the compiled IMBE encoder and decoder (src/p25/native).

    python tools/build_native.py

The pure Python encoder (src/p25/imbe.py) and decoder (src/p25/mbe_decoder.py)
work everywhere but are slow: the encoder runs at about real time on a fast
PC. This builds both as one C shared library - the encoder bit-identical to
the Python one, the decoder matching it to rounding - which the app loads
automatically when it's there and falls back from when it isn't.

Needs a C compiler:
  Linux / Alpine   cc or gcc  (Alpine: apk add build-base)
  Windows          Visual Studio or its Build Tools ("Desktop development with C++")
  macOS            Xcode command line tools

The encoder tables are generated from src/p25/tables.py, so the C and Python
encoders always use the same values.
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NATIVE = os.path.join(ROOT, 'src', 'p25', 'native')
sys.path.insert(0, ROOT)

from src.p25 import mbe_tables as M  # noqa: E402
from src.p25 import tables as T  # noqa: E402

SOURCES = ('imbe_enc.c', 'imbe_dec.c')

# name in tables.py -> C element type
TABLES = {
    'BIT_ALLOCATION_TBL': 'int32_t',
    'BIT_ALLOCATION_OFFSET_TBL': 'int32_t',
    'LMPRBL_TBL': 'uint32_t',
    'GAIN_QNT_TBL': 'int32_t',
    'GAIN_STEP_SIZE_TBL': 'int32_t',
    'HI_ORD_STD_TBL': 'int32_t',
    'HI_ORD_STEP_SIZE_TBL': 'int32_t',
    'WI': 'int32_t',
    'WR': 'int32_t',
    'WR_SP': 'int32_t',
    'MIN_MAX_TBL': 'int32_t',
    'LPF_COEF': 'int32_t',
    'COS_TABLE': 'int32_t',
    'SQRT_TABLE': 'int32_t',
    'LOG_TABLE': 'int32_t',
}


def write_tables() -> str:
    lines = ['/* Generated by tools/build_native.py from src/p25/tables.py - do not edit. */',
             '#ifndef IMBE_TABLES_H', '#define IMBE_TABLES_H', '#include <stdint.h>', '']
    for name, ctype in TABLES.items():
        values = getattr(T, name)
        suffix = 'u' if ctype == 'uint32_t' else ''
        body = []
        for i in range(0, len(values), 10):
            body.append('    ' + ', '.join(f'{v}{suffix}' for v in values[i:i + 10]) + ',')
        lines += [f'static const {ctype} {name}[{len(values)}] = {{'] + body + ['};', '']
    lines.append('#endif')
    path = os.path.join(NATIVE, 'imbe_tables.h')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    return path


def write_mbe_tables() -> str:
    """Decoder tables, as doubles (repr round-trips exactly)."""
    def num(v):
        return repr(float(v))

    def rows(values, per=8):
        return ['    ' + ', '.join(values[i:i + per]) + ',' for i in range(0, len(values), per)]

    lines = ['/* Generated by tools/build_native.py from src/p25/mbe_tables.py - do not edit. */',
             '#ifndef MBE_TABLES_H', '#define MBE_TABLES_H', '#include <stdint.h>', '']
    for name in ('B2', 'QUANTSTEP', 'STANDDEV', 'WS'):
        values = getattr(M, name)
        lines += [f'static const double {name}[{len(values)}] = {{'] + rows([num(v) for v in values]) + ['};', '']
    n = len(M.BA)
    lines.append(f'static const int BA_BITS[{n}][5] = {{')
    lines += ['    {' + ', '.join(str(int(b)) for b, _ in r) + '},' for r in M.BA] + ['};', '']
    lines.append(f'static const double BA_STEP[{n}][5] = {{')
    lines += ['    {' + ', '.join(num(st) for _, st in r) + '},' for r in M.BA] + ['};', '']
    lines.append(f'static const uint8_t BO[{n}][79][2] = {{')
    lines += ['    {' + ', '.join(f'{{{a}, {b}}}' for a, b in r) + '},' for r in M.BO] + ['};', '']
    for name, width in (('HOBA', 50), ('IMBEJI', 6)):
        lines.append(f'static const int {name}[{n}][{width}] = {{')
        lines += ['    {' + ', '.join(str(int(v)) for v in r) + '},' for r in getattr(M, name)] + ['};', '']
    lines.append('#endif')
    path = os.path.join(NATIVE, 'mbe_tables.h')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    return path


def lib_name() -> str:
    return '_imbe.dll' if sys.platform == 'win32' else ('_imbe.dylib' if sys.platform == 'darwin' else '_imbe.so')


def find_vcvars() -> str:
    vswhere = os.path.join(os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)'),
                           'Microsoft Visual Studio', 'Installer', 'vswhere.exe')
    if os.path.exists(vswhere):
        out = subprocess.run([vswhere, '-latest', '-products', '*', '-requires',
                              'Microsoft.VisualStudio.Component.VC.Tools.x86.x64', '-property', 'installationPath'],
                             capture_output=True, text=True).stdout.strip()
        if out:
            path = os.path.join(out.splitlines()[0], 'VC', 'Auxiliary', 'Build', 'vcvars64.bat')
            if os.path.exists(path):
                return path
    raise SystemExit('No Visual Studio C++ compiler found. Install Visual Studio (or its Build Tools) '
                     'with "Desktop development with C++".')


def build() -> str:
    srcs = [os.path.join(NATIVE, f) for f in SOURCES]
    out = os.path.join(NATIVE, lib_name())
    if sys.platform == 'win32':
        vcvars = find_vcvars()
        # A running service keeps the DLL open, so it can't be overwritten -
        # but it can be renamed out of the way (the service keeps the old
        # one until it restarts).
        stale = out + '.old'
        if os.path.exists(stale):
            try:
                os.remove(stale)
            except OSError:
                pass                    # still loaded by a service from an earlier build
        if os.path.exists(out):
            try:
                os.remove(out)
            except OSError:
                os.replace(out, stale)
        # a batch file keeps cmd's quoting out of it
        quoted = ' '.join(f'"{x}"' for x in srcs)
        bat = os.path.join(NATIVE, '_build.bat')
        with open(bat, 'w', encoding='ascii') as f:
            f.write('@echo off\r\n'
                    'set "PATH=%ProgramFiles(x86)%\\Microsoft Visual Studio\\Installer;%PATH%"\r\n'
                    f'call "{vcvars}" >nul || exit /b 1\r\n'
                    f'cl /nologo /O2 /LD /W3 {quoted} /Fe:"{out}"\r\n')
        try:
            result = subprocess.run(['cmd', '/d', '/c', bat], cwd=NATIVE, capture_output=True, text=True)
        finally:
            os.remove(bat)
        for ext in ('.obj', '.lib', '.exp'):
            p = os.path.join(NATIVE, '_imbe' + ext)
            if os.path.exists(p):
                os.remove(p)
        for f in SOURCES:
            obj = os.path.join(NATIVE, f[:-2] + '.obj')
            if os.path.exists(obj):
                os.remove(obj)
    else:
        cc = os.environ.get('CC') or shutil.which('cc') or shutil.which('gcc') or shutil.which('clang')
        if not cc:
            raise SystemExit('No C compiler found (Alpine: apk add build-base, Debian: apt install build-essential).')
        flags = ['-O2', '-shared', '-fPIC', '-Wall']
        result = subprocess.run([cc, *flags, '-o', out, *srcs, '-lm'], cwd=NATIVE, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stdout.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit('Build failed.')
    return out


def main():
    print(f'Tables: {write_tables()}')
    print(f'Tables: {write_mbe_tables()}')
    out = build()
    print(f'Built:  {out}')
    from src.p25 import imbe_native
    imbe_native.load(force=True)
    if not imbe_native.available():
        raise SystemExit(f'Built, but it would not load: {imbe_native.load_error()}')
    print('The compiled encoder and decoder load. Check they match the Python ones with:\n'
          '    python -m unittest tests.test_imbe_native')


if __name__ == '__main__':
    main()
